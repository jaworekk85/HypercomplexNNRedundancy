"""Render manuscript tables and citation subset from canonical project evidence.

Read-only with respect to numerical studies and the root bibliography.
Run from any directory: python paper/prepare.py
"""
import hashlib
import json
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent


def read_json(relative):
    return json.loads((ROOT / relative).read_text(encoding="utf-8-sig"))


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def table(name, caption, label, columns, header, rows):
    contents = [
        "% Generated by prepare.py; do not hand-edit numerical cells.",
        r"\begin{table}[t]", r"\centering\footnotesize",
        r"\caption{" + caption + "}", r"\label{" + label + "}",
        r"\begin{tabular}{" + columns + "}", r"\toprule",
        header + r" \\", r"\midrule",
        *[row + r" \\" for row in rows],
        r"\bottomrule", r"\end{tabular}", r"\end{table}", "",
    ]
    (HERE / "tables" / (name + ".tex")).write_text("\n".join(contents), encoding="utf-8")


def main():
    (HERE / "tables").mkdir(exist_ok=True)
    source_paths = [
        "results/eurosat_grouping_fp32_replication/cross_dataset_summary.json",
        "results/grouping_mechanism_study/summary.json",
        "results/eurosat_grouping_fp32_replication/summary.json",
        "results/grouping_statistics_control/INTERPRETATION.md",
        "results/component_reassembly_diagnostic/summary.json",
        "results/grouping_mechanism_study/parent_validation_replays.json",
        "results/eurosat_grouping_fp32_replication/parent_replays.json",
    ]
    cross = read_json(source_paths[0])
    cifar = read_json(source_paths[1])
    eurosat = read_json(source_paths[2])
    cases = ("original", "role_100_0", "free_100_0")
    names = {"original": "Original", "role_100_0": "Role-preserving", "free_100_0": "Role-free"}
    assert not cifar["test_evaluated"] and not eurosat["official_test_evaluated"]
    assert len(cifar["results"]) == 15 and len(eurosat["results"]) == 9
    means, seed_rows, budget_rows = [], [], []
    verified_means, parent_means = {}, {}
    for ds, source, name in zip(cross["datasets"], (cifar, eurosat), ("CIFAR-10", "EuroSAT")):
        assert ds["source_seed_count"] == 3
        parent, compact = ds["parent_real_parameters"], ds["compact_real_parameters"]
        savings = 100 * (1 - compact / parent)
        assert abs(savings - ds["whole_model_savings_percent"]) < 1e-10
        counts = {r["real_trainable_parameters"] for r in source["results"]}
        assert counts == {compact}, counts
        attempts = ds["attempted_updates_per_model"]
        assert len(attempts) == 1
        budget_rows.append(f"{name} & {parent:,} & {compact:,} & {savings:.2f}\\% & {attempts[0]:,}")
        means.append(r"\multicolumn{4}{c}{" + name + "}")
        parent_replays = read_json(source_paths[5 if name == "CIFAR-10" else 6])
        assert sorted(parent_replays) == ["2026", "2027", "2028"]
        parent_accuracy = 100 * sum(r["validation"]["accuracy"] for r in parent_replays.values()) / 3
        parent_means[name] = parent_accuracy
        means.append(f"Uncompressed parent & {parent_accuracy:.2f} & --- & ---")
        lookup = {(r["seed"], r["case"]): r for r in source["results"]}
        assert len(lookup) == len(source["results"])
        verified_means[name] = {}
        for case in cases:
            records = [lookup[(seed, case)] for seed in (2026, 2027, 2028)]
            before = 100 * sum(r["before"]["validation"]["accuracy"] for r in records) / 3
            after = 100 * sum(r["after"]["validation"]["accuracy"] for r in records) / 3
            ce = sum(r["after"]["validation"]["cross_entropy"] for r in records) / 3
            aggregate = next(r for r in ds["aggregates"] if r["case"] == case)
            assert abs(before - aggregate["before"]["accuracy_percent"]) < 1e-10
            assert abs(after - aggregate["after"]["accuracy_percent"]) < 1e-10
            assert abs(ce - aggregate["after"]["cross_entropy"]) < 1e-10
            means.append(f"{names[case]} & {before:.2f} & {after:.2f} & {ce:.4f}")
            verified_means[name][case] = {"before_percent": before, "after_percent": after, "final_ce": ce}
        seed_rows.append(r"\multicolumn{4}{c}{" + name + "}")
        for seed in (2026, 2027, 2028):
            values = [100 * lookup[(seed, case)]["after"]["validation"]["accuracy"] for case in cases]
            assert values[0] > values[1] and values[0] > values[2]
            seed_rows.append(str(seed) + " & " + " & ".join(f"{v:.1f}" for v in values))
    table("budgets", "Actual whole-model real trainables and repair attempts per model. Successful updates: 1,125 on CIFAR; 459--461 on EuroSAT.",
          "tab:budgets", "lrrrr", "Setting & Parent & Compact & Saved & Attempts", budget_rows)
    table("accuracy", "Validation accuracy (\\%) and final cross-entropy, descriptive means over three source seeds. Parent rows give source accuracy only. Compact mixed conditions use the first prespecified grouping and three repair epochs.",
          "tab:accuracy", "lrrr", "Grouping & Before & After & Final CE", means)
    table("seeds", "Final validation accuracy (\\%) for individual source seeds. These are paired conditions, not nine independent parents per setting.",
          "tab:seeds", "lrrr", "Source seed & Original & Role-preserving & Role-free", seed_rows)
    # Registered counts are extracted from the interpretation's measured-results table,
    # rather than recomputing a new statistical endpoint from the completed study.
    interpretation = (ROOT / source_paths[3]).read_text(encoding="utf-8")
    statistics_rows = []
    for source_label, label in (("Native", "Native"), ("BN recalibrated", "BN"),
                                ("BN recalibrated + standardized (primary)", "BN + standardized")):
        match = re.search(r"^\| " + re.escape(source_label) + r" \| (\d+) \| (\d+) \|$", interpretation, re.M)
        if match is None:
            raise ValueError(f"Measured statistics row missing: {source_label}")
        statistics_rows.append(f"{label} & {match[1]}/12 & {match[2]}/12")
    table("statistics", "Positive trained-minus-initial increments in normalized mixing penalty. Counts pair source seed, site and policy; they are not independent training replications.",
          "tab:statistics", "lrr", "Diagnostic state & CIFAR-10 & EuroSAT", statistics_rows)
    local_rows, local_means = [], []
    for block, site in ((0, "Early"), (8, "Late")):
        for case in cases:
            prefix = case[:-1] if case != "original" else None
            rows = [r for r in cifar["local_results"] if r["block"] == block and
                    (r["case"].startswith(prefix) if prefix else r["case"] == case)]
            assert len(rows) == (3 if case == "original" else 30)
            exact = sum(r["ideal"]["check_mse"] for r in rows) / len(rows)
            physical = sum(r["physical"]["check_mse"] for r in rows) / len(rows)
            local_rows.append(f"{site} & {names[case]} & {exact:.4f} & {physical:.4f}")
            local_means.append({"block": block, "case": case, "paired_source_seeds": 3,
                                "draws_per_seed": 1 if case == "original" else 10,
                                "exact_check_mse": exact, "physical_check_mse": physical})
    table("local_reconstruction", "CIFAR consumer CHECK MSE on exact retained features and physically compiled producers. Original: mean of three parents; fully mixed: mean over ten fixed draws within each of the same three parents. Raw MSE scales differ by site; draws are not independent training seeds.",
          "tab:local", "llrr", "Site & Grouping & Exact & Physical", local_rows)
    toy = read_json(source_paths[4])
    assert toy["synthetic_only"] and not toy["test_evaluated"]
    toy_lookup = {(r["case"], r["method"]): r for r in toy["results"]}
    toy_rows, toy_results = [], []
    for case, label in (("aligned_complementary", "Nearby"), ("unrelated_complementary", "Independent")):
        whole = toy_lookup[(case, "best_whole_unit")]
        regrouped = toy_lookup[(case, "realizable_selection")]
        for method in ("scalar_energy", "consumer_only_selection", "realizable_selection"):
            selected = toy_lookup[(case, method)]
            assert selected["quartet"] == regrouped["quartet"] == [0, 3, 4, 7]
            assert selected["counts"]["real_parameters"] == 16
        assert whole["counts"]["real_parameters"] == 16
        assert regrouped["ideal_check_mse"] < 1e-12
        assert regrouped["check_mse"] < whole["check_mse"]
        toy_rows.append(f"{label} & {whole['check_mse']:.4f} & $<10^{{-12}}$ & {regrouped['check_mse']:.4f}")
        toy_results.append({"case": case, "whole_check_mse": whole["check_mse"],
                            "reassembled_ideal_check_mse": regrouped["ideal_check_mse"],
                            "reassembled_physical_check_mse": regrouped["check_mse"],
                            "reassembled_producer_projection_sse": regrouped["producer_kernel_squared_error"],
                            "all_scalar_selectors_choose_same_quartet": True})
    table("synthetic", "Constructed synthetic examples: held-out output MSE. Whole is the best original quartet; reassembled columns use full-teacher selected features (ideal) or the smaller producer (physical). All students store 16 real trainables versus 32 in each teacher. These examples allow the retained scalar set to change.",
          "tab:synthetic", "lrrr", "Producer relation & Whole & Reassembled ideal & Physical", toy_rows)
    variants = [r for r in cifar["local_results"] if "datafit" in r]
    assert len(variants) == 12
    feature_improvements = sum(r["datafit"]["fit"]["producer_feature_mse"]["check_calibration"] <
                               r["physical"]["producer_feature_mse"]["check_calibration"] for r in variants)
    output_worsenings = sum(r["datafit"]["fit"]["check_mse"] > r["physical"]["check_mse"] for r in variants)
    assert (feature_improvements, output_worsenings) == (12, 4)

    # The canonical database uses one field per line. Preserve each selected
    # entry verbatim except its internal provenance note, which is inappropriate
    # for printing as a publication bibliography. No bibliographic metadata is
    # inferred or downloaded here.
    canonical = ROOT / "references.bib"
    chunks = re.split(r"(?=^@\w+\{)", canonical.read_text(encoding="utf-8"), flags=re.M)
    entries = {}
    for chunk in chunks:
        match = re.match(r"@\w+\{([^,]+),", chunk)
        if match:
            key = match[1]
            if key in entries:
                raise ValueError(f"Duplicate canonical citation key: {key}")
            note_lines = [line for line in chunk.splitlines() if re.match(r"\s*note\s*=", line)]
            if any(not re.search(r"\},?\s*$", line) for line in note_lines):
                raise ValueError("Multiline note requires a full BibTeX parser")
            entries[key] = re.sub(r"^\s*note\s*=.*\n", "", chunk, flags=re.M).strip()
    main_tex = (HERE / "main.tex").read_text(encoding="utf-8")
    cite_lists = re.findall(r"\\cite(?:\[[^\]]*\])?\{([^}]+)\}", main_tex)
    citations = sorted({key.strip() for group in cite_lists for key in group.split(",")})
    missing = set(citations) - entries.keys()
    if missing:
        raise ValueError(f"Missing canonical citations: {sorted(missing)}")
    bib = "% Generated from ../references.bib by prepare.py; internal provenance notes omitted.\n\n"
    bib += "\n\n".join(entries[key] for key in citations) + "\n"
    (HERE / "references.bib").write_text(bib, encoding="utf-8")
    manifest = {
        "status": "exploratory manuscript draft; human review and final test evaluation pending",
        "sources_sha256": {p: digest(ROOT / p) for p in source_paths + ["references.bib"]},
        "citation_keys": citations,
        "canonical_entry_count": len(entries),
        "means_recomputed_from_seed_results": verified_means,
        "parent_accuracy_means_from_saved_replays": parent_means,
        "producer_feature_improvements": feature_improvements,
        "consumer_output_worsenings": output_worsenings,
        "local_reconstruction_means": local_means,
        "constructed_synthetic_checks": toy_results,
        "generated_sha256": {str(p.relative_to(HERE)).replace('\\', '/'): digest(p)
                             for p in sorted((HERE / "tables").glob("*.tex"))},
    }
    manifest["generated_sha256"]["references.bib"] = digest(HERE / "references.bib")
    (HERE / "evidence.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"Prepared 6 tables and {len(citations)} canonical citations; 24 model rows, 126 local rows and 8 synthetic rows checked.")


if __name__ == "__main__":
    main()
